func (p *v2WireProvider) UnmarshalJSON(data []byte) error {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}
	id := peekJSONString(raw["id"])
	if id == "" {
		id = "?"
	}
	for _, legacy := range []string{"protocol", "api_key", "api_keys", "models", "models_source"} {
		if _, ok := raw[legacy]; ok {
			return fmt.Errorf("v2 provider %q has legacy field %q", id, legacy)
		}
	}
	groupsRaw, ok := raw["groups"]
	if !ok {
		return fmt.Errorf("provider %q missing groups field", id)
	}
	var groups []ProviderGroup
	if err := json.Unmarshal(groupsRaw, &groups); err != nil {
		return fmt.Errorf("provider %q groups: %w", id, err)
	}
	if len(groups) == 0 {
		return fmt.Errorf("provider %q has empty groups", id)
	}
	for _, group := range groups {
		if strings.TrimSpace(group.Protocol) == "" {
			return fmt.Errorf("provider %q group %q missing protocol", id, group.ID)
		}
	}

	type plain struct {
		ID               string            `json:"id"`
		Name             string            `json:"name"`
		BaseURL          string            `json:"base_url"`
		BaseURLs         []string          `json:"base_urls"`
		BaseURLStrategy  string            `json:"base_url_strategy"`
		Headers          map[string]string `json:"headers"`
		Disabled         bool              `json:"disabled"`
		AutoAliasEnabled *bool             `json:"auto_alias_enabled"`
	}
	var out plain
	if err := json.Unmarshal(data, &out); err != nil {
		return err
	}
	p.ID = out.ID
	p.Name = out.Name
	p.BaseURL = out.BaseURL
	p.BaseURLs = out.BaseURLs
	p.BaseURLStrategy = out.BaseURLStrategy
	p.Headers = out.Headers
	p.Disabled = out.Disabled
	p.AutoAliasEnabled = out.AutoAliasEnabled
	p.Groups = groups
	return nil
}

