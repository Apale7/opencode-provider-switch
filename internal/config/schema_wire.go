func decodeV2Config(data []byte) (*Config, error) {
	var wire v2WireConfig
	if err := json.Unmarshal(data, &wire); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	c := Default()
	c.SchemaVersion = CurrentSchemaVersion
	c.Server = wire.Server
	c.Admin = wire.Admin
	c.Desktop = wire.Desktop
	c.ProviderPriority = cloneStrings(wire.ProviderPriority)
	if wire.AutoAliasEnabled != nil {
		c.AutoAliasEnabled = *wire.AutoAliasEnabled
	}

	c.Providers = make([]Provider, 0, len(wire.Providers))
	for _, wp := range wire.Providers {
		p := Provider{
			ID:               wp.ID,
			Name:             wp.Name,
			BaseURL:          wp.BaseURL,
			BaseURLs:         cloneStrings(wp.BaseURLs),
			BaseURLStrategy:  wp.BaseURLStrategy,
			Headers:          cloneStringMap(wp.Headers),
			Disabled:         wp.Disabled,
			AutoAliasEnabled: cloneBoolPtr(wp.AutoAliasEnabled),
			Groups:           cloneProviderGroups(wp.Groups),
		}
		c.Providers = append(c.Providers, p)
	}

	c.Aliases = make([]Alias, 0, len(wire.Aliases))
	for _, wa := range wire.Aliases {
		a := Alias{
			Alias:           wa.Alias,
			DisplayName:     wa.DisplayName,
			Protocol:        wa.Protocol,
			Enabled:         wa.Enabled,
			AutoGenerated:   wa.AutoGenerated,
			Locked:          wa.Locked,
			TargetOrderMode: storageTargetOrderMode(wa.TargetOrderMode),
			Targets:         make([]Target, 0, len(wa.Targets)),
		}
		for _, wt := range wa.Targets {
			group := strings.TrimSpace(wt.Group)
			if !wt.groupPresent || group == "" {
				return nil, fmt.Errorf("alias %q target missing non-empty group", wa.Alias)
			}
			a.Targets = append(a.Targets, Target{
				Provider:      wt.Provider,
				Group:         group,
				Model:         wt.Model,
				Enabled:       wt.Enabled,
				AutoGenerated: wt.AutoGenerated,
			})
		}
		c.Aliases = append(c.Aliases, a)
	}

	c.RequestRewriteRules = make([]RequestRewriteRule, 0, len(wire.RequestRewriteRules))
	for _, wr := range wire.RequestRewriteRules {
		rule := RequestRewriteRule{
			Name:     wr.Name,
			Alias:    wr.Alias,
			Enabled:  wr.Enabled,
			Override: wr.Override,
			Ops:      cloneRequestRewriteOperations(wr.Ops),
			Set:      cloneAnyMap(wr.Set),
			Delete:   cloneStrings(wr.Delete),
		}
		if wr.providerGroupsPresent {
			rule.ProviderGroups = cloneProviderGroupSelectors(wr.ProviderGroups)
			if rule.ProviderGroups == nil {
				rule.ProviderGroups = []ProviderGroupSelector{}
			}
		} else {
			// Omitted provider_groups treated as wildcard empty list for runtime.
			rule.ProviderGroups = []ProviderGroupSelector{}
		}
		c.RequestRewriteRules = append(c.RequestRewriteRules, rule)
	}
	return c, nil
}

func peekJSONString(raw json.RawMessage) string {
	if len(raw) == 0 {
		return ""
	}
	var s string
	if err := json.Unmarshal(raw, &s); err != nil {
		return ""
	}
	return s
}

func cloneBoolPtr(in *bool) *bool {
	if in == nil {
		return nil
	}
	v := *in
	return &v
}

// BackupPathForConfig returns the sibling backup path used before schema upgrades.
func BackupPathForConfig(path string) string {
	return path + ".bak"
}

// NeedsLegacyConfigBackup reports whether base disk bytes are not yet schema v2.
func NeedsLegacyConfigBackup(baseRaw []byte) bool {
	if len(bytes.TrimSpace(baseRaw)) == 0 {
		return false
	}
	var probe struct {
		SchemaVersion json.RawMessage `json:"schema_version"`
	}
	if err := json.Unmarshal(baseRaw, &probe); err != nil {
		return true
	}
	version, legacy, err := parseSchemaVersion(probe.SchemaVersion)
	if err != nil {
		return true
	}
	if legacy {
		return true
	}
	return version != CurrentSchemaVersion
}
