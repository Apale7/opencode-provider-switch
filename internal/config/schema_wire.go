func decodeV1Config(data []byte) (*Config, error) {
	var wire v1WireConfig
	if err := json.Unmarshal(data, &wire); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	c := Default()
	c.Server = wire.Server
	c.Admin = wire.Admin
	c.Desktop = wire.Desktop
	c.ProviderPriority = cloneStrings(wire.ProviderPriority)
	if wire.AutoAliasEnabled != nil {
		c.AutoAliasEnabled = *wire.AutoAliasEnabled
	}

	providers, providerRefs := migrateV1Providers(wire.Providers)
	c.Providers = providers

	c.Aliases = make([]Alias, 0, len(wire.Aliases))
	for _, wa := range wire.Aliases {
		a := Alias{
			Alias:           wa.Alias,
			DisplayName:     wa.DisplayName,
			Protocol:        wa.Protocol,
			Enabled:         wa.Enabled,
			AutoGenerated:   wa.AutoGenerated,
			Locked:          wa.Locked,
			TargetOrderMode: storageTargetOrderMode(wa.TargetOrderMode),
			Targets:         make([]Target, 0, len(wa.Targets)),
		}
		for _, wt := range wa.Targets {
			provider, group := migrateV1ProviderRef(providerRefs, wt.Provider)
			a.Targets = append(a.Targets, Target{
				Provider:      provider,
				Group:         group,
				Model:         wt.Model,
				Enabled:       wt.Enabled,
				AutoGenerated: wt.AutoGenerated,
			})
		}
		c.Aliases = append(c.Aliases, a)
	}

	c.RequestRewriteRules = make([]RequestRewriteRule, 0, len(wire.RequestRewriteRules))
	for _, wr := range wire.RequestRewriteRules {
		rule := RequestRewriteRule{
			Name:     wr.Name,
			Alias:    wr.Alias,
			Enabled:  wr.Enabled,
			Override: wr.Override,
			Ops:      cloneRequestRewriteOperations(wr.Ops),
			Set:      cloneAnyMap(wr.Set),
			Delete:   cloneStrings(wr.Delete),
		}
		if wr.providersPresent && len(wr.Providers) > 0 {
			seen := map[string]bool{}
			for _, providerID := range wr.Providers {
				providerID = strings.TrimSpace(providerID)
				if providerID == "" || seen[providerID] {
					continue
				}
				seen[providerID] = true
				provider, group := migrateV1ProviderRef(providerRefs, providerID)
				rule.ProviderGroups = append(rule.ProviderGroups, ProviderGroupSelector{
					Provider: provider,
					Group:    group,
				})
			}
		} else {
			// Empty or omitted providers → explicit wildcard (empty provider_groups).
			rule.ProviderGroups = []ProviderGroupSelector{}
		}
		c.RequestRewriteRules = append(c.RequestRewriteRules, rule)
	}
	c.ProviderPriority = migrateV1ProviderPriority(providerRefs, c.ProviderPriority)
	return c, nil
}

type v1ProviderRef struct {
	Provider string
	Group    string
}

type v1ProviderCluster struct {
	base    v1WireProvider
	members []v1WireProvider
}

// migrateV1Providers groups legacy providers which share the complete set of
// provider-level connection settings. The returned refs translate every old
// provider identity to its retained provider and group identity.
func migrateV1Providers(in []v1WireProvider) ([]Provider, map[string]v1ProviderRef) {
	clusters := make([]v1ProviderCluster, 0, len(in))
	for _, wp := range in {
		placed := false
		for i := range clusters {
			if v1ProvidersShareConnection(clusters[i].base, wp) {
				clusters[i].members = append(clusters[i].members, wp)
				placed = true
				break
			}
		}
		if !placed {
			clusters = append(clusters, v1ProviderCluster{base: wp, members: []v1WireProvider{wp}})
		}
	}

	providers := make([]Provider, 0, len(clusters))
	refs := make(map[string]v1ProviderRef, len(in))
	for _, cluster := range clusters {
		base := cluster.base
		p := Provider{
			ID:               base.ID,
			Name:             base.Name,
			BaseURL:          base.BaseURL,
			BaseURLs:         cloneStrings(base.BaseURLs),
			BaseURLStrategy:  base.BaseURLStrategy,
			Headers:          cloneStringMap(base.Headers),
			Disabled:         len(cluster.members) == 1 && base.Disabled,
			AutoAliasEnabled: cloneBoolPtr(base.AutoAliasEnabled),
			Groups:           make([]ProviderGroup, 0, len(cluster.members)),
		}
		usedGroups := map[string]bool{}
		for i, member := range cluster.members {
			groupID := DefaultGroupID
			if i > 0 {
				groupID = legacyProviderGroupID(member.ID, i+1, usedGroups)
			}
			usedGroups[groupID] = true
			groupName := strings.TrimSpace(member.Name)
			if len(cluster.members) == 1 || groupName == "" {
				groupName = DefaultGroupName
			}
			p.Groups = append(p.Groups, ProviderGroup{
				ID:           groupID,
				Name:         groupName,
				Protocol:     member.Protocol,
				APIKey:       member.APIKey,
				APIKeys:      cloneStrings(member.APIKeys),
				Models:       cloneStrings(member.Models),
				ModelsSource: member.ModelsSource,
				Disabled:     len(cluster.members) > 1 && member.Disabled,
			})
			refs[member.ID] = v1ProviderRef{Provider: base.ID, Group: groupID}
		}
		providers = append(providers, p)
	}
	return providers, refs
}

func v1ProvidersShareConnection(a, b v1WireProvider) bool {
	if len(a.BaseURLs) == 0 && len(b.BaseURLs) == 0 &&
		NormalizeProviderBaseURL(a.BaseURL) == "" && NormalizeProviderBaseURL(b.BaseURL) == "" {
		return false
	}
	return reflect.DeepEqual(NormalizeProviderBaseURLs(a.BaseURL, a.BaseURLs), NormalizeProviderBaseURLs(b.BaseURL, b.BaseURLs)) &&
		NormalizeProviderBaseURLStrategy(a.BaseURLStrategy) == NormalizeProviderBaseURLStrategy(b.BaseURLStrategy) &&
		v1ProviderHeadersEqual(a.Headers, b.Headers) &&
		legacyAutoAliasEnabled(a.AutoAliasEnabled) == legacyAutoAliasEnabled(b.AutoAliasEnabled)
}

func v1ProviderHeadersEqual(a, b map[string]string) bool {
	if len(a) == 0 && len(b) == 0 {
		return true
	}
	normalize := func(headers map[string]string) map[string]string {
		out := make(map[string]string, len(headers))
		for key, value := range headers {
			key = strings.ToLower(strings.TrimSpace(key))
			if key == "" {
				continue
			}
			out[key] = strings.TrimSpace(value)
		}
		return out
	}
	return reflect.DeepEqual(normalize(a), normalize(b))
}

func legacyAutoAliasEnabled(value *bool) bool {
	if value == nil {
		return true
	}
	return *value
}

func legacyProviderGroupID(providerID string, ordinal int, used map[string]bool) string {
	id := strings.TrimSpace(providerID)
	if id == "" || used[id] {
		id = fmt.Sprintf("group-%d", ordinal)
		for used[id] {
			ordinal++
			id = fmt.Sprintf("group-%d", ordinal)
		}
	}
	return id
}

func migrateV1ProviderRef(refs map[string]v1ProviderRef, providerID string) (string, string) {
	if ref, ok := refs[providerID]; ok {
		return ref.Provider, ref.Group
	}
	return providerID, DefaultGroupID
}

func migrateV1ProviderPriority(refs map[string]v1ProviderRef, priority []string) []string {
	out := make([]string, 0, len(priority))
	seen := map[string]bool{}
	for _, providerID := range priority {
		providerID = strings.TrimSpace(providerID)
		if providerID == "" {
			continue
		}
		provider, _ := migrateV1ProviderRef(refs, providerID)
		if seen[provider] {
			continue
		}
		seen[provider] = true
		out = append(out, provider)
	}
	return out
}

