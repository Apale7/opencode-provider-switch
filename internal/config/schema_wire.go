// decodeConfigJSON parses on-disk config bytes into the runtime model.
// schema v1 / missing version migrate into a unique default group in memory only.
func decodeConfigJSON(data []byte) (*Config, error) {
	if len(bytes.TrimSpace(data)) == 0 {
		c := Default()
		return c, nil
	}

	var probe struct {
		SchemaVersion json.RawMessage `json:"schema_version"`
	}
	if err := json.Unmarshal(data, &probe); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}

	version, legacy, err := parseSchemaVersion(probe.SchemaVersion)
	if err != nil {
		return nil, err
	}
	if legacy {
		cfg, err := decodeV1Config(data)
		if err != nil {
			return nil, err
		}
		cfg.SchemaVersion = CurrentSchemaVersion
		cfg.loadedFromLegacy = true
		return cfg, nil
	}
	switch version {
	case CurrentSchemaVersion:
		cfg, err := decodeV2Config(data)
		if err != nil {
			return nil, err
		}
		cfg.SchemaVersion = CurrentSchemaVersion
		cfg.loadedFromLegacy = false
		return cfg, nil
	default:
		return nil, fmt.Errorf("unsupported schema version %d", version)
	}
}

// parseSchemaVersion distinguishes missing (legacy), integer 1/2, and invalid forms.
// missing → legacy=true; null / non-integer / unknown → error.
func parseSchemaVersion(raw json.RawMessage) (version int, legacy bool, err error) {
	if len(raw) == 0 {
		return 0, true, nil
	}
	trimmed := bytes.TrimSpace(raw)
	if bytes.Equal(trimmed, []byte("null")) {
		return 0, false, fmt.Errorf("unsupported schema version")
	}
	// Reject strings/bools/objects/arrays: only JSON number tokens are accepted.
	// (json.Number is a string under the hood and would accept a quoted "2".)
	if len(trimmed) == 0 || (trimmed[0] != '-' && (trimmed[0] < '0' || trimmed[0] > '9')) {
		return 0, false, fmt.Errorf("unsupported schema version")
	}
	dec := json.NewDecoder(bytes.NewReader(trimmed))
	dec.UseNumber()
	var num json.Number
	if err := dec.Decode(&num); err != nil {
		return 0, false, fmt.Errorf("unsupported schema version")
	}
	// Reject floats and non-integer encodings.
	if strings.ContainsAny(num.String(), ".eE") {
		return 0, false, fmt.Errorf("unsupported schema version")
	}
	n, err := num.Int64()
	if err != nil {
		return 0, false, fmt.Errorf("unsupported schema version")
	}
	if n == 1 {
		return 1, true, nil
	}
	if n == int64(CurrentSchemaVersion) {
		return CurrentSchemaVersion, false, nil
	}
	return int(n), false, fmt.Errorf("unsupported schema version %d", n)
}

