func (p *v1WireProvider) UnmarshalJSON(data []byte) error {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}
	if _, ok := raw["groups"]; ok {
		id := peekJSONString(raw["id"])
		if id == "" {
			id = "?"
		}
		return fmt.Errorf("mixed schema format: provider %q has groups field under schema v1/legacy", id)
	}
	type plain v1WireProvider
	var out plain
	if err := json.Unmarshal(data, &out); err != nil {
		return err
	}
	*p = v1WireProvider(out)
	return nil
}

