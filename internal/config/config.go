// Target is one concrete upstream candidate for an alias.
type Target struct {
	Provider      string `json:"provider"`
	Model         string `json:"model"`
	Enabled       bool   `json:"enabled"`
	AutoGenerated bool   `json:"auto_generated,omitempty"` // 是否由系统自动添加
}

// TargetRef identifies one alias target without mutable state.
type TargetRef struct {
	Provider string
	Model    string
}

// RequestRewriteRule rewrites outbound request config for a matching alias and
// selected target provider list. Empty Providers means all providers for that
// alias. Set and Delete are legacy fields kept only to detect inactive old rules.
type RequestRewriteRule struct {
	Name      string                    `json:"name"`
	Alias     string                    `json:"alias,omitempty"`
	Providers []string                  `json:"providers,omitempty"`
	Enabled   bool                      `json:"enabled"`
	Override  bool                      `json:"override,omitempty"`
	Ops       []RequestRewriteOperation `json:"ops,omitempty"`
	Set       map[string]any            `json:"set,omitempty"`
	Delete    []string                  `json:"delete,omitempty"`
}

// Alias maps a logical model name to ordered upstream targets.
type Alias struct {
	Alias         string   `json:"alias"`
	DisplayName   string   `json:"display_name,omitempty"`
	Protocol      string   `json:"protocol,omitempty"`
	Enabled       bool     `json:"enabled"`
	Targets       []Target `json:"targets"`
	AutoGenerated bool     `json:"auto_generated,omitempty"` // 是否由系统自动生成
	Locked        bool     `json:"locked,omitempty"`         // 是否锁定（禁止自动修改）
}

// Provider is one upstream OpenAI-compatible endpoint.
type Provider struct {
	ID              string            `json:"id"`
	Name            string            `json:"name,omitempty"`
	Protocol        string            `json:"protocol,omitempty"`
	BaseURL         string            `json:"base_url"`
	BaseURLs        []string          `json:"base_urls,omitempty"`
	BaseURLStrategy string            `json:"base_url_strategy,omitempty"`
	APIKey          string            `json:"api_key"`
	APIKeys         []string          `json:"api_keys,omitempty"`
	Headers         map[string]string `json:"headers,omitempty"`
	Models          []string          `json:"models,omitempty"`
	ModelsSource    string            `json:"models_source,omitempty"`
	Disabled        bool              `json:"disabled,omitempty"`
	// AutoAliasEnabled controls per-provider auto-alias generation.
	// Nil means enabled (legacy configs default to true).
	AutoAliasEnabled *bool `json:"auto_alias_enabled,omitempty"`
}

const (
	ProviderBaseURLStrategyOrdered = "ordered"
	ProviderBaseURLStrategyLatency = "latency"
)

// Server holds proxy listen settings.
type Server struct {
	Host                             string         `json:"host"`
	Port                             int            `json:"port"`
	APIKey                           string         `json:"api_key"`
	ConnectTimeoutMs                 int            `json:"connect_timeout_ms,omitempty"`
	ResponseHeaderTimeoutMs          int            `json:"response_header_timeout_ms,omitempty"`
	FirstByteTimeoutMs               int            `json:"first_byte_timeout_ms,omitempty"`
	RequestReadTimeoutMs             int            `json:"request_read_timeout_ms,omitempty"`
	StreamIdleTimeoutMs              int            `json:"stream_idle_timeout_ms,omitempty"`
	StreamPrecommitBufferMs          int            `json:"stream_precommit_buffer_ms,omitempty"`
	ExcludeFirstTokenLatencyFromRate bool           `json:"exclude_first_token_latency_from_rate"`
	FailoverStatusCodes              []int          `json:"failover_status_codes"`
	Routing                          routing.Config `json:"routing,omitempty"`
}

// Admin holds the server-mode web administration listener and token.
type Admin struct {
	Host          string `json:"host,omitempty"`
	Port          int    `json:"port,omitempty"`
	APIKey        string `json:"api_key,omitempty"`
	PublicBaseURL string `json:"public_base_url,omitempty"`
}

const (
	DefaultConnectTimeoutMs                 = 10_000
	DefaultResponseHeaderTimeoutMs          = 15_000
	DefaultFirstByteTimeoutMs               = 15_000
	DefaultRequestReadTimeoutMs             = 30_000
	DefaultStreamIdleTimeoutMs              = 60_000
	DefaultStreamPrecommitBufferMs          = 0
	DefaultExcludeFirstTokenLatencyFromRate = true
)

