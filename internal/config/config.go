// DefaultPath returns ~/.config/ocswitch/config.json (XDG aware).
func DefaultPath() string {
	if p := os.Getenv(ConfigEnvVar); p != "" {
		return p
	}
	if xdg := os.Getenv("XDG_CONFIG_HOME"); xdg != "" {
		return filepath.Join(xdg, ConfigDirName, "config.json")
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return AppName + "-config.json"
	}
	return filepath.Join(home, ".config", ConfigDirName, "config.json")
}

// Load reads the config at path. Missing file returns a default config anchored to path.
// Load never writes disk and never changes ConfigStore revision.
func Load(path string) (*Config, error) {
	if path == "" {
		path = DefaultPath()
	}
	data, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			c := Default()
			c.path = path
			return c, nil
		}
		return nil, fmt.Errorf("read config: %w", err)
	}
	return finalizeLoadedConfig(path, data)
}

func configHasExplicitServerAPIKey(data []byte) bool {
	var raw struct {
		Server *struct {
			APIKey *string `json:"api_key"`
		} `json:"server"`
	}
	if err := json.Unmarshal(data, &raw); err != nil {
		return false
	}
	return raw.Server != nil && raw.Server.APIKey != nil
}

// Path returns the on-disk path of this config.
func (c *Config) Path() string {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.path
}

// MarshalPersistent encodes config using the same normalization and field set as Save.
func (c *Config) MarshalPersistent() ([]byte, error) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.marshalPersistentLocked()
}

func (c *Config) marshalPersistentLocked() ([]byte, error) {
	providers := cloneProviders(c.Providers)
	normalizeProviders(providers)
	sort.Slice(providers, func(i, j int) bool { return providers[i].ID < providers[j].ID })
	aliases := cloneAliases(c.Aliases)
	normalizeAliases(aliases)
	sort.Slice(aliases, func(i, j int) bool { return aliases[i].Alias < aliases[j].Alias })
	rewriteRules := cloneRequestRewriteRules(c.RequestRewriteRules)
	normalizeRequestRewriteRules(rewriteRules)
	server := c.Server
	normalizeServerTimeouts(&server)
	normalizeServerFailoverStatusCodes(&server)
	normalizeServerRouting(&server)

	// Canonical v2 wire shape — never emit deprecated provider projections or legacy rewrite providers.
	type persistGroup struct {
		ID           string   `json:"id"`
		Name         string   `json:"name,omitempty"`
		Protocol     string   `json:"protocol"`
		APIKey       string   `json:"api_key,omitempty"`
		APIKeys      []string `json:"api_keys,omitempty"`
		Models       []string `json:"models,omitempty"`
		ModelsSource string   `json:"models_source,omitempty"`
		Disabled     bool     `json:"disabled,omitempty"`
	}
	type persistProvider struct {
		ID               string            `json:"id"`
		Name             string            `json:"name,omitempty"`
		BaseURL          string            `json:"base_url"`
		BaseURLs         []string          `json:"base_urls,omitempty"`
		BaseURLStrategy  string            `json:"base_url_strategy,omitempty"`
		Headers          map[string]string `json:"headers,omitempty"`
		Disabled         bool              `json:"disabled,omitempty"`
		AutoAliasEnabled *bool             `json:"auto_alias_enabled,omitempty"`
		Groups           []persistGroup    `json:"groups"`
	}
	type persistTarget struct {
		Provider      string `json:"provider"`
		Group         string `json:"group"`
		Model         string `json:"model"`
		Enabled       bool   `json:"enabled"`
		AutoGenerated bool   `json:"auto_generated,omitempty"`
	}
	type persistAlias struct {
		Alias         string          `json:"alias"`
		DisplayName   string          `json:"display_name,omitempty"`
		Protocol      string          `json:"protocol,omitempty"`
		Enabled       bool            `json:"enabled"`
		Targets       []persistTarget `json:"targets"`
		AutoGenerated bool            `json:"auto_generated,omitempty"`
		Locked        bool            `json:"locked,omitempty"`
	}
	type persistRewrite struct {
		Name           string                    `json:"name"`
		Alias          string                    `json:"alias,omitempty"`
		ProviderGroups []ProviderGroupSelector   `json:"provider_groups,omitempty"`
		Enabled        bool                      `json:"enabled"`
		Override       bool                      `json:"override,omitempty"`
		Ops            []RequestRewriteOperation `json:"ops,omitempty"`
		Set            map[string]any            `json:"set,omitempty"`
		Delete         []string                  `json:"delete,omitempty"`
	}

	outProviders := make([]persistProvider, 0, len(providers))
	for _, p := range providers {
		groups := make([]persistGroup, 0, len(p.Groups))
		for _, g := range p.Groups {
			groups = append(groups, persistGroup{
				ID:           g.ID,
				Name:         g.Name,
				Protocol:     g.Protocol,
				APIKey:       g.APIKey,
				APIKeys:      g.APIKeys,
				Models:       g.Models,
				ModelsSource: g.ModelsSource,
				Disabled:     g.Disabled,
			})
		}
		outProviders = append(outProviders, persistProvider{
			ID:               p.ID,
			Name:             p.Name,
			BaseURL:          p.BaseURL,
			BaseURLs:         p.BaseURLs,
			BaseURLStrategy:  p.BaseURLStrategy,
			Headers:          p.Headers,
			Disabled:         p.Disabled,
			AutoAliasEnabled: p.AutoAliasEnabled,
			Groups:           groups,
		})
	}
	outAliases := make([]persistAlias, 0, len(aliases))
	for _, a := range aliases {
		targets := make([]persistTarget, 0, len(a.Targets))
		for _, t := range a.Targets {
			// Do not rewrite empty group to default; only the v1 decoder injects default.
			// Validate/ValidateForPersist fail closed on empty target groups.
			targets = append(targets, persistTarget{
				Provider:      t.Provider,
				Group:         strings.TrimSpace(t.Group),
				Model:         t.Model,
				Enabled:       t.Enabled,
				AutoGenerated: t.AutoGenerated,
			})
		}
		outAliases = append(outAliases, persistAlias{
			Alias:         a.Alias,
			DisplayName:   a.DisplayName,
			Protocol:      a.Protocol,
			Enabled:       a.Enabled,
			Targets:       targets,
			AutoGenerated: a.AutoGenerated,
			Locked:        a.Locked,
		})
	}
	outRules := make([]persistRewrite, 0, len(rewriteRules))
	for _, rule := range rewriteRules {
		// Always emit provider_groups key when the slice is non-nil (including explicit empty wildcard).
		item := persistRewrite{
			Name:     rule.Name,
			Alias:    rule.Alias,
			Enabled:  rule.Enabled,
			Override: rule.Override,
			Ops:      rule.Ops,
			Set:      rule.Set,
			Delete:   rule.Delete,
		}
		if rule.ProviderGroups != nil {
			item.ProviderGroups = rule.ProviderGroups
		}
		outRules = append(outRules, item)
	}

	snap := struct {
		SchemaVersion       int               `json:"schema_version"`
		Server              Server            `json:"server"`
		Admin               Admin             `json:"admin,omitempty"`
		Desktop             Desktop           `json:"desktop,omitempty"`
		Providers           []persistProvider `json:"providers"`
		Aliases             []persistAlias    `json:"aliases"`
		RequestRewriteRules []persistRewrite  `json:"request_rewrite_rules,omitempty"`
		ProviderPriority    []string          `json:"provider_priority,omitempty"`
		// Persist explicitly so false is not dropped by omitempty on reload.
		AutoAliasEnabled bool `json:"auto_alias_enabled"`
	}{
		SchemaVersion:       CurrentSchemaVersion,
		Server:              server,
		Admin:               c.Admin,
		Desktop:             c.Desktop,
		Providers:           outProviders,
		Aliases:             outAliases,
		RequestRewriteRules: outRules,
		ProviderPriority:    cloneStrings(c.ProviderPriority),
		AutoAliasEnabled:    c.AutoAliasEnabled,
	}
	data, err := json.MarshalIndent(snap, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	// Ensure empty provider_groups arrays are preserved (omitempty would drop them).
	data, err = ensureEmptyProviderGroupsJSON(data, rewriteRules)
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// ensureEmptyProviderGroupsJSON rewrites rules that intentionally use empty
// provider_groups wildcard so omitempty does not drop the key.
func ensureEmptyProviderGroupsJSON(data []byte, rules []RequestRewriteRule) ([]byte, error) {
	needs := false
	for _, rule := range rules {
		if rule.ProviderGroups != nil && len(rule.ProviderGroups) == 0 {
			needs = true
			break
		}
	}
	if !needs {
		return data, nil
	}
	var root map[string]any
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	if err := decoder.Decode(&root); err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	rawRules, _ := root["request_rewrite_rules"].([]any)
	if len(rawRules) != len(rules) {
		return data, nil
	}
	for i, rule := range rules {
		if rule.ProviderGroups == nil || len(rule.ProviderGroups) != 0 {
			continue
		}
		item, ok := rawRules[i].(map[string]any)
		if !ok {
			continue
		}
		item["provider_groups"] = []any{}
		rawRules[i] = item
	}
	root["request_rewrite_rules"] = rawRules
	out, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	return out, nil
}

// LoadFromBytes decodes config JSON for path without reading disk.
// Missing/empty data returns a default config anchored to path, matching Load.
// LoadFromBytes never writes disk and never changes ConfigStore revision.
func LoadFromBytes(path string, data []byte) (*Config, error) {
	if path == "" {
		path = DefaultPath()
	}
	return finalizeLoadedConfig(path, data)
}

func finalizeLoadedConfig(path string, data []byte) (*Config, error) {
	if len(data) == 0 {
		c := Default()
		c.path = path
		return c, nil
	}
	serverAPIKeyExplicit := configHasExplicitServerAPIKey(data)
	c, err := decodeConfigJSON(data)
	if err != nil {
		return nil, err
	}
	normalizeProviders(c.Providers)
	normalizeAliases(c.Aliases)
	normalizeRequestRewriteRules(c.RequestRewriteRules)
	c.ProviderPriority = c.normalizeProviderPriorityLocked(c.ProviderPriority)
	c.reorderUnlockedAutoAliasTargetsLocked()
	if c.Server.Host == "" {
		c.Server.Host = "127.0.0.1"
	}
	if c.Server.Port == 0 {
		c.Server.Port = 9982
	}
	if c.Server.APIKey == "" && !serverAPIKeyExplicit {
		c.Server.APIKey = DefaultLocalAPIKey
	}
	normalizeAdmin(&c.Admin)
	normalizeServerTimeouts(&c.Server)
	normalizeServerFailoverStatusCodes(&c.Server)
	normalizeServerRouting(&c.Server)
	c.SchemaVersion = CurrentSchemaVersion
	c.path = path
	return c, nil
}

// CloneDeep returns a detached deep copy of exported config fields.
func (c *Config) CloneDeep() (*Config, error) {
	raw, err := c.MarshalPersistent()
	if err != nil {
		return nil, err
	}
	return LoadFromBytes(c.Path(), raw)
}

// Save writes config atomically as schema v2.
// When the existing file is legacy schema, a sibling .bak is written first.
// Backup failure must not overwrite the original file.
func (c *Config) Save() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.path == "" {
		c.path = DefaultPath()
	}
	path := c.path
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("mkdir: %w", err)
	}
	return fileutil.WithLockedFile(path, func() error {
		data, err := c.marshalPersistentLocked()
		if err != nil {
			return err
		}
		if err := BackupLegacyConfigFile(path); err != nil {
			return err
		}
		if err := fileutil.AtomicWriteFile(path, data, 0o600); err != nil {
			return err
		}
		c.loadedFromLegacy = false
		c.SchemaVersion = CurrentSchemaVersion
		return nil
	})
}

// BackupLegacyConfigFile writes path.bak from the current file when it is not schema v2.
// It is shared by Config.Save and transactional ConfigStore persistence hooks.
// An existing regular .bak file is preserved (first backup wins). A directory or
// unwritable backup target remains an error so callers can abort the upgrade write.
func BackupLegacyConfigFile(path string) error {
	existing, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("read config for backup: %w", err)
	}
	if !NeedsLegacyConfigBackup(existing) {
		return nil
	}
	backupPath := BackupPathForConfig(path)
	info, statErr := os.Stat(backupPath)
	if statErr == nil {
		if info.IsDir() {
			return fmt.Errorf("backup legacy config: %s is a directory", backupPath)
		}
		// First backup already present; never overwrite it.
		return nil
	}
	if !errors.Is(statErr, os.ErrNotExist) {
		return fmt.Errorf("stat legacy backup: %w", statErr)
	}
	if err := fileutil.AtomicWriteFile(backupPath, existing, 0o600); err != nil {
		return fmt.Errorf("backup legacy config: %w", err)
	}
	return nil
}

// FindProvider returns the provider with matching id or nil.
func (c *Config) FindProvider(id string) *Provider {
	c.mu.RLock()
	defer c.mu.RUnlock()
	p := c.findProviderLocked(id)
	if p == nil {
		return nil
	}
	clone := cloneProvider(*p)
	return &clone
}

func (c *Config) findProviderLocked(id string) *Provider {
	for i := range c.Providers {
		if c.Providers[i].ID == id {
			return &c.Providers[i]
		}
	}
	return nil
}

// UpsertProvider adds or replaces a provider by id.
// Empty Groups are stored as-is; only the v1 decoder injects a default group.
// Validate / ValidateForPersist fail closed when a provider has no groups.
func (c *Config) UpsertProvider(p Provider) {
	c.mu.Lock()
	defer c.mu.Unlock()
	cloned := cloneProvider(p)
	for i := range c.Providers {
		if c.Providers[i].ID == p.ID {
			c.Providers[i] = cloned
			return
		}
	}
	c.Providers = append(c.Providers, cloned)
}

// RemoveProvider deletes a provider and returns true if removed.
func (c *Config) RemoveProvider(id string) bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	for i := range c.Providers {
		if c.Providers[i].ID == id {
			c.Providers = append(c.Providers[:i], c.Providers[i+1:]...)
			return true
		}
	}
	return false
}

