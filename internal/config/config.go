func requestRewriteRuleMatches(rule RequestRewriteRule, aliasName, provider, group string) bool {
	if rule.Alias == "" {
		return false
	}
	if rule.Alias != aliasName {
		return false
	}
	group = strings.TrimSpace(group)
	if group == "" {
		return false
	}
	if rule.ProviderGroups == nil || len(rule.ProviderGroups) == 0 {
		return true
	}
	for _, selector := range rule.ProviderGroups {
		if strings.TrimSpace(selector.Provider) == provider && strings.TrimSpace(selector.Group) == group {
			return true
		}
	}
	return false
}

// AddTarget appends a target to an alias; creates alias if missing.
func (c *Config) AddTarget(alias string, t Target) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	t.Group = strings.TrimSpace(t.Group)
	if t.Group == "" {
		return fmt.Errorf("target group is required")
	}
	for i := range c.Aliases {
		if c.Aliases[i].Alias == alias {
			// prevent exact duplicate
			for _, x := range c.Aliases[i].Targets {
				xg := strings.TrimSpace(x.Group)
				if x.Provider == t.Provider && xg == t.Group && x.Model == t.Model {
					return fmt.Errorf("target %s/%s/%s already bound to alias %s", t.Provider, t.Group, t.Model, alias)
				}
			}
			c.Aliases[i].Targets = append(c.Aliases[i].Targets, t)
			return nil
		}
	}
	return fmt.Errorf("alias %q not found", alias)
}

// RemoveTarget is a legacy wrapper that removes a target from the default group.
// Prefer RemoveTargetFromGroup with an explicit group.
func (c *Config) RemoveTarget(alias, provider, model string) error {
	return c.RemoveTargetFromGroup(alias, provider, DefaultGroupID, model)
}

// RemoveTargetFromGroup removes a target by provider+group+model.
func (c *Config) RemoveTargetFromGroup(alias, provider, group, model string) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	group = strings.TrimSpace(group)
	if group == "" {
		return fmt.Errorf("target group is required")
	}
	for i := range c.Aliases {
		if c.Aliases[i].Alias != alias {
			continue
		}
		out := c.Aliases[i].Targets[:0]
		found := false
		for _, t := range c.Aliases[i].Targets {
			tg := strings.TrimSpace(t.Group)
			if t.Provider == provider && tg == group && t.Model == model {
				found = true
				continue
			}
			out = append(out, t)
		}
		if !found {
			return fmt.Errorf("target %s/%s/%s not found on alias %s", provider, group, model, alias)
		}
		c.Aliases[i].Targets = out
		return nil
	}
	return fmt.Errorf("alias %q not found", alias)
}

// ReorderTargets replaces an alias target order while preserving target state.
func (c *Config) ReorderTargets(alias string, refs []TargetRef) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	for i := range c.Aliases {
		if c.Aliases[i].Alias != alias {
			continue
		}
		current := c.Aliases[i].Targets
		if len(refs) != len(current) {
			return fmt.Errorf("alias %s reorder target count mismatch: got %d, want %d", alias, len(refs), len(current))
		}
		byRef := make(map[TargetRef]Target, len(current))
		for _, target := range current {
			group := strings.TrimSpace(target.Group)
			if group == "" {
				return fmt.Errorf("alias %s has target without group", alias)
			}
			ref := TargetRef{Provider: target.Provider, Group: group, Model: target.Model}
			if _, exists := byRef[ref]; exists {
				return fmt.Errorf("alias %s has duplicate target %s/%s/%s", alias, target.Provider, group, target.Model)
			}
			byRef[ref] = target
		}
		seen := make(map[TargetRef]bool, len(refs))
		next := make([]Target, 0, len(refs))
		for _, ref := range refs {
			ref.Provider = strings.TrimSpace(ref.Provider)
			ref.Group = strings.TrimSpace(ref.Group)
			ref.Model = strings.TrimSpace(ref.Model)
			if ref.Provider == "" || ref.Group == "" || ref.Model == "" {
				return fmt.Errorf("target provider, group and model are required")
			}
			if seen[ref] {
				return fmt.Errorf("duplicate target %s/%s/%s in reorder request", ref.Provider, ref.Group, ref.Model)
			}
			target, ok := byRef[ref]
			if !ok {
				return fmt.Errorf("target %s/%s/%s not found on alias %s", ref.Provider, ref.Group, ref.Model, alias)
			}
			seen[ref] = true
			next = append(next, target)
		}
		c.Aliases[i].Targets = next
		return nil
	}
	return fmt.Errorf("alias %q not found", alias)
}

// AvailableTargets returns alias targets that are individually enabled and point
// at providers that still exist and are enabled.
func (c *Config) AvailableTargets(alias Alias) []Target {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.availableTargetsLocked(alias)
}

func (c *Config) availableTargetsLocked(alias Alias) []Target {
	targets := make([]Target, 0, len(alias.Targets))
	for _, t := range alias.Targets {
		if !t.Enabled {
			continue
		}
		provider := c.findProviderLocked(t.Provider)
		if provider == nil || !provider.IsEnabled() {
			continue
		}
		view := cloneProvider(*provider)
		groupID := strings.TrimSpace(t.Group)
		if groupID == "" {
			continue
		}
		group := view.FindGroup(groupID)
		if group == nil || !group.IsEnabled() {
			continue
		}
		if !ProtocolsMatch(alias.Protocol, group.Protocol) {
			continue
		}
		targets = append(targets, t)
	}
	return targets
}

