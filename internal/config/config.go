// FindProvidersByModel returns enabled providers whose Models exactly contain
// model, ordered by the full provider priority list.
func (c *Config) FindProvidersByModel(model string) []Provider {
	c.mu.RLock()
	defer c.mu.RUnlock()
	model = strings.TrimSpace(model)
	if model == "" {
		return nil
	}
	matched := make(map[string]Provider, len(c.Providers))
	for _, p := range c.Providers {
		if !p.IsEnabled() {
			continue
		}
		found := false
		for _, g := range p.Groups {
			if providerModelsContain(g.Models, model) {
				found = true
				break
			}
		}
		if !found {
			continue
		}
		matched[p.ID] = cloneProvider(p)
	}
	if len(matched) == 0 {
		return nil
	}
	order := c.providerPriorityOrderLocked()
	out := make([]Provider, 0, len(matched))
	for _, id := range order {
		if p, ok := matched[id]; ok {
			out = append(out, p)
		}
	}
	return out
}

