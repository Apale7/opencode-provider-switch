func normalizeRequestRewriteRules(rules []RequestRewriteRule) {
	for i := range rules {
		rules[i] = normalizeRequestRewriteRule(rules[i])
	}
}

func normalizeRequestRewriteRule(rule RequestRewriteRule) RequestRewriteRule {
	rule.Name = strings.TrimSpace(rule.Name)
	rule.Alias = strings.TrimSpace(rule.Alias)
	if len(rule.Providers) > 0 {
		seen := map[string]bool{}
		next := make([]string, 0, len(rule.Providers))
		for _, provider := range rule.Providers {
			trimmed := strings.TrimSpace(provider)
			if trimmed == "" || seen[trimmed] {
				continue
			}
			seen[trimmed] = true
			next = append(next, trimmed)
		}
		rule.Providers = next
	} else {
		rule.Providers = nil
	}
	if len(rule.Set) > 0 {
		next := make(map[string]any, len(rule.Set))
		for key, value := range rule.Set {
			trimmed := strings.TrimSpace(key)
			if trimmed == "" {
				continue
			}
			next[trimmed] = cloneJSONValue(value)
		}
		rule.Set = next
	} else {
		rule.Set = nil
	}
	if len(rule.Delete) > 0 {
		seen := map[string]bool{}
		next := make([]string, 0, len(rule.Delete))
		for _, key := range rule.Delete {
			trimmed := strings.TrimSpace(key)
			if trimmed == "" || seen[trimmed] {
				continue
			}
			seen[trimmed] = true
			next = append(next, trimmed)
		}
		rule.Delete = next
	} else {
		rule.Delete = nil
	}
	if len(rule.Ops) > 0 {
		next := make([]RequestRewriteOperation, 0, len(rule.Ops))
		for _, op := range rule.Ops {
			op = normalizeRequestRewriteOperation(op)
			if op.Op == "" && op.Path == "" {
				continue
			}
			next = append(next, op)
		}
		rule.Ops = next
	} else {
		rule.Ops = nil
	}
	return rule
}

