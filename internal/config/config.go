// LockAutoAlias marks an auto-generated alias as locked so automatic generation
// and cleanup no longer modify it. The alias remains AutoGenerated=true.
// Returns a clone of the locked alias.
func (c *Config) LockAutoAlias(name string) (Alias, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	name = strings.TrimSpace(name)
	if name == "" {
		return Alias{}, fmt.Errorf("alias name is required")
	}
	idx := c.findAliasIndexLocked(name)
	if idx < 0 {
		return Alias{}, fmt.Errorf("alias %q not found", name)
	}
	a := &c.Aliases[idx]
	if !a.AutoGenerated {
		return Alias{}, fmt.Errorf("alias %q is not auto-generated", name)
	}
	a.Locked = true
	return cloneAlias(*a), nil
}

// AutoGenerateAliases creates or updates unlocked auto-generated aliases for each
// enabled Provider Group's models. Targets use the precise triple
// (provider, group, model); same model in different groups remains independent.
// Manual and locked aliases are left untouched. Disabled providers, disabled
// groups, and auto-alias switches (global or per-provider) produce zero changes.
func (c *Config) AutoGenerateAliases(provider Provider) (created []string, updated []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if !c.AutoAliasEnabled || !provider.EffectiveAutoAliasEnabled() || provider.Disabled {
		return nil, nil
	}
	providerID := strings.TrimSpace(provider.ID)
	if providerID == "" {
		return nil, nil
	}
	createdSet := map[string]bool{}
	updatedSet := map[string]bool{}
	for _, group := range provider.Groups {
		if group.Disabled {
			continue
		}
		groupID := strings.TrimSpace(group.ID)
		if groupID == "" {
			continue
		}
		protocol := NormalizeProviderProtocol(group.Protocol)
		for _, model := range group.Models {
			model = strings.TrimSpace(model)
			if model == "" {
				continue
			}
			idx := c.findAliasIndexLocked(model)
			if idx < 0 {
				alias := Alias{
					Alias:         model,
					Protocol:      protocol,
					Enabled:       true,
					AutoGenerated: true,
					Targets: []Target{{
						Provider:      providerID,
						Group:         groupID,
						Model:         model,
						Enabled:       true,
						AutoGenerated: true,
					}},
				}
				c.Aliases = append(c.Aliases, cloneAlias(alias))
				if !createdSet[model] {
					createdSet[model] = true
					created = append(created, model)
				}
				continue
			}
			a := &c.Aliases[idx]
			if !a.AutoGenerated || a.Locked {
				continue
			}
			if !ProtocolsMatch(a.Protocol, protocol) {
				continue
			}
			if targetExists(a.Targets, providerID, groupID, model) {
				continue
			}
			a.Targets = append(a.Targets, Target{
				Provider:      providerID,
				Group:         groupID,
				Model:         model,
				Enabled:       true,
				AutoGenerated: true,
			})
			a.Targets = c.sortTargetsByPriorityLocked(a.Targets)
			if !updatedSet[model] && !createdSet[model] {
				updatedSet[model] = true
				updated = append(updated, model)
			}
		}
	}
	return created, updated
}

// ReconcileProviderGroupAutoTargets removes stale system-owned targets for one
// trusted group catalog. Manual aliases, locked aliases, and manual targets are preserved.
func (c *Config) ReconcileProviderGroupAutoTargets(providerID, groupID string, models []string) (removed []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	providerID = strings.TrimSpace(providerID)
	groupID = strings.TrimSpace(groupID)
	if providerID == "" || groupID == "" {
		return nil
	}
	allowed := make(map[string]bool, len(models))
	for _, model := range models {
		if model = strings.TrimSpace(model); model != "" {
			allowed[model] = true
		}
	}
	aliases := make([]Alias, 0, len(c.Aliases))
	for _, alias := range c.Aliases {
		if !alias.AutoGenerated || alias.Locked {
			aliases = append(aliases, alias)
			continue
		}
		targets := alias.Targets[:0]
		changed := false
		for _, target := range alias.Targets {
			stale := target.AutoGenerated && target.Provider == providerID &&
				strings.TrimSpace(target.Group) == groupID && !allowed[strings.TrimSpace(target.Model)]
			if stale {
				changed = true
				continue
			}
			targets = append(targets, target)
		}
		alias.Targets = targets
		if changed {
			removed = append(removed, alias.Alias)
		}
		if len(alias.Targets) > 0 {
			aliases = append(aliases, alias)
		}
	}
	c.Aliases = aliases
	return removed
}

// RemoveProviderAutoTargets removes targets for providerID from unlocked
// auto-generated aliases. Aliases left with no targets are deleted; their names
// are returned in emptied. Manual aliases are not modified.
func (c *Config) RemoveProviderAutoTargets(providerID string) (emptied []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	providerID = strings.TrimSpace(providerID)
	if providerID == "" {
		return nil
	}
	next := c.Aliases[:0]
	for i := range c.Aliases {
		a := c.Aliases[i]
		if !a.AutoGenerated || a.Locked {
			next = append(next, a)
			continue
		}
		kept := a.Targets[:0]
		for _, t := range a.Targets {
			if t.Provider == providerID {
				continue
			}
			kept = append(kept, t)
		}
		a.Targets = kept
		if len(a.Targets) == 0 {
			emptied = append(emptied, a.Alias)
			continue
		}
		next = append(next, a)
	}
	// Ensure Aliases is never nil-slice vs empty inconsistency if all removed.
	if len(next) == 0 {
		c.Aliases = []Alias{}
	} else {
		c.Aliases = next
	}
	return emptied
}

// RemoveGroupAutoTargets removes system-owned targets for (providerID, groupID)
// from unlocked auto-generated aliases. Aliases left with no targets are deleted;
// their names are returned in emptied. Manual and locked aliases are not modified.
// Does not rebind to default or sibling groups.
func (c *Config) RemoveGroupAutoTargets(providerID, groupID string) (emptied []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	providerID = strings.TrimSpace(providerID)
	groupID = strings.TrimSpace(groupID)
	if providerID == "" || groupID == "" {
		return nil
	}
	next := c.Aliases[:0]
	for i := range c.Aliases {
		a := c.Aliases[i]
		if !a.AutoGenerated || a.Locked {
			next = append(next, a)
			continue
		}
		kept := a.Targets[:0]
		for _, t := range a.Targets {
			tg := strings.TrimSpace(t.Group)
			// Only clear system-owned targets for the precise group; protect manual targets.
			if t.Provider == providerID && tg == groupID && t.AutoGenerated {
				continue
			}
			kept = append(kept, t)
		}
		a.Targets = kept
		if len(a.Targets) == 0 {
			emptied = append(emptied, a.Alias)
			continue
		}
		next = append(next, a)
	}
	if len(next) == 0 {
		c.Aliases = []Alias{}
	} else {
		c.Aliases = next
	}
	return emptied
}

func (c *Config) findAliasIndexLocked(name string) int {
	for i := range c.Aliases {
		if c.Aliases[i].Alias == name {
			return i
		}
	}
	return -1
}

func (c *Config) providerPriorityOrderLocked() []string {
	return c.normalizeProviderPriorityLocked(c.ProviderPriority)
}

func (c *Config) normalizeProviderPriorityLocked(ids []string) []string {
	known := make(map[string]bool, len(c.Providers))
	for _, p := range c.Providers {
		if p.ID == "" {
			continue
		}
		known[p.ID] = true
	}
	seen := make(map[string]bool, len(c.Providers))
	out := make([]string, 0, len(c.Providers))
	for _, id := range ids {
		id = strings.TrimSpace(id)
		if id == "" || !known[id] || seen[id] {
			continue
		}
		seen[id] = true
		out = append(out, id)
	}
	for _, p := range c.Providers {
		if p.ID == "" || seen[p.ID] {
			continue
		}
		seen[p.ID] = true
		out = append(out, p.ID)
	}
	return out
}

func (c *Config) reorderUnlockedAutoAliasTargetsLocked() {
	for i := range c.Aliases {
		a := &c.Aliases[i]
		if !a.AutoGenerated || a.Locked {
			continue
		}
		a.Targets = c.sortTargetsByPriorityLocked(a.Targets)
	}
}

func (c *Config) sortTargetsByPriorityLocked(targets []Target) []Target {
	if len(targets) <= 1 {
		return cloneTargets(targets)
	}
	order := c.providerPriorityOrderLocked()
	rank := make(map[string]int, len(order))
	for i, id := range order {
		rank[id] = i
	}
	out := cloneTargets(targets)
	sort.SliceStable(out, func(i, j int) bool {
		ri, oki := rank[out[i].Provider]
		rj, okj := rank[out[j].Provider]
		if !oki {
			ri = len(order)
		}
		if !okj {
			rj = len(order)
		}
		if ri != rj {
			return ri < rj
		}
		// Same provider: keep independent group targets ordered stably by group then model.
		// Empty group is not rewritten to default (fail closed; only v1 decoder injects default).
		gi := strings.TrimSpace(out[i].Group)
		gj := strings.TrimSpace(out[j].Group)
		if gi != gj {
			return gi < gj
		}
		return out[i].Model < out[j].Model
	})
	return out
}

func providerModelsContain(models []string, model string) bool {
	for _, item := range models {
		if item == model {
			return true
		}
	}
	return false
}

func targetExists(targets []Target, providerID, groupID, model string) bool {
	groupID = strings.TrimSpace(groupID)
	for _, t := range targets {
		tg := strings.TrimSpace(t.Group)
		if t.Provider == providerID && tg == groupID && t.Model == model {
			return true
		}
	}
	return false
}

