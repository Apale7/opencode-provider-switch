// Config is the on-disk ocswitch config.
type Config struct {
	Server    Server     `json:"server"`
	Admin     Admin      `json:"admin,omitempty"`
	Desktop   Desktop    `json:"desktop,omitempty"`
	Providers []Provider `json:"providers"`
	Aliases   []Alias    `json:"aliases"`

	RequestRewriteRules []RequestRewriteRule `json:"request_rewrite_rules,omitempty"`
	ProviderPriority    []string             `json:"provider_priority,omitempty"`  // 按优先级排序的 provider ID 列表
	AutoAliasEnabled    bool                 `json:"auto_alias_enabled,omitempty"` // 全局自动 alias 开关（默认 true）

	path string
	mu   sync.RWMutex
}

// IsEnabled reports whether the provider can be used for routing.
func (p Provider) IsEnabled() bool {
	return !p.Disabled
}

// EffectiveAutoAliasEnabled reports whether this provider participates in
// automatic alias generation. Nil (legacy) defaults to true.
func (p Provider) EffectiveAutoAliasEnabled() bool {
	if p.AutoAliasEnabled == nil {
		return true
	}
	return *p.AutoAliasEnabled
}

// IsAutoAliasEnabled is equivalent to EffectiveAutoAliasEnabled.
func (p Provider) IsAutoAliasEnabled() bool {
	return p.EffectiveAutoAliasEnabled()
}

// EffectiveBaseURLs returns the provider's normalized upstream base URL list.
func (p Provider) EffectiveBaseURLs() []string {
	return NormalizeProviderBaseURLs(p.BaseURL, p.BaseURLs)
}

// EffectiveAPIKeys returns the provider's normalized upstream API key list.
func (p Provider) EffectiveAPIKeys() []string {
	return NormalizeProviderAPIKeys(p.APIKey, p.APIKeys)
}

// NormalizeProviderBaseURL canonicalizes equivalent /v1 roots for comparisons
// and persisted config values.
func NormalizeProviderBaseURL(baseURL string) string {
	return strings.TrimRight(strings.TrimSpace(baseURL), "/")
}

// NormalizeProviderBaseURLs canonicalizes, deduplicates, and preserves order.
func NormalizeProviderBaseURLs(primary string, baseURLs []string) []string {
	combined := make([]string, 0, len(baseURLs)+1)
	if primary != "" {
		combined = append(combined, primary)
	}
	combined = append(combined, baseURLs...)
	seen := map[string]bool{}
	out := make([]string, 0, len(combined))
	for _, item := range combined {
		normalized := NormalizeProviderBaseURL(item)
		if normalized == "" || seen[normalized] {
			continue
		}
		seen[normalized] = true
		out = append(out, normalized)
	}
	return out
}

// NormalizeProviderAPIKeys canonicalizes, deduplicates, and preserves order.
func NormalizeProviderAPIKeys(primary string, apiKeys []string) []string {
	combined := make([]string, 0, len(apiKeys)+1)
	if primary != "" {
		combined = append(combined, primary)
	}
	combined = append(combined, apiKeys...)
	seen := map[string]bool{}
	out := make([]string, 0, len(combined))
	for _, item := range combined {
		trimmed := strings.TrimSpace(item)
		if trimmed == "" || seen[trimmed] {
			continue
		}
		seen[trimmed] = true
		out = append(out, trimmed)
	}
	return out
}

func NormalizeProviderBaseURLStrategy(strategy string) string {
	switch strings.TrimSpace(strategy) {
	case "", ProviderBaseURLStrategyOrdered:
		return ProviderBaseURLStrategyOrdered
	case ProviderBaseURLStrategyLatency:
		return ProviderBaseURLStrategyLatency
	default:
		return ProviderBaseURLStrategyOrdered
	}
}

func ValidateProviderBaseURLStrategy(strategy string) error {
	strategy = NormalizeProviderBaseURLStrategy(strategy)
	if strategy == ProviderBaseURLStrategyOrdered || strategy == ProviderBaseURLStrategyLatency {
		return nil
	}
	return fmt.Errorf("unknown base_url_strategy %q", strategy)
}

func ValidateProviderBaseURLs(protocol string, primary string, baseURLs []string) error {
	urls := NormalizeProviderBaseURLs(primary, baseURLs)
	if len(urls) == 0 {
		return fmt.Errorf("missing base_url")
	}
	for _, item := range urls {
		if err := ValidateProviderBaseURL(protocol, item); err != nil {
			return err
		}
	}
	return nil
}

// ValidateProviderBaseURL checks protocol-specific upstream base URL rules.
func ValidateProviderBaseURL(protocol string, baseURL string) error {
	protocol = NormalizeProviderProtocol(protocol)
	if err := ValidateProtocol(protocol); err != nil {
		return err
	}
	trimmed := NormalizeProviderBaseURL(baseURL)
	if trimmed == "" {
		return fmt.Errorf("missing base_url")
	}
	return nil
}

// Default returns an empty config with sane defaults.
func Default() *Config {
	return &Config{
		Server: Server{
			Host:                             "127.0.0.1",
			Port:                             9982,
			APIKey:                           DefaultLocalAPIKey,
			ConnectTimeoutMs:                 DefaultConnectTimeoutMs,
			ResponseHeaderTimeoutMs:          DefaultResponseHeaderTimeoutMs,
			FirstByteTimeoutMs:               DefaultFirstByteTimeoutMs,
			RequestReadTimeoutMs:             DefaultRequestReadTimeoutMs,
			StreamIdleTimeoutMs:              DefaultStreamIdleTimeoutMs,
			StreamPrecommitBufferMs:          DefaultStreamPrecommitBufferMs,
			ExcludeFirstTokenLatencyFromRate: DefaultExcludeFirstTokenLatencyFromRate,
			FailoverStatusCodes:              DefaultFailoverStatusCodes(),
			Routing:                          routing.Config{Strategy: routing.DefaultStrategy},
		},
		Admin: Admin{
			Host: "127.0.0.1",
			Port: 9983,
		},
		Desktop:             Desktop{},
		Providers:           []Provider{},
		Aliases:             []Alias{},
		RequestRewriteRules: []RequestRewriteRule{},
		ProviderPriority:    []string{},
		AutoAliasEnabled:    true,
	}
}

// DefaultPath returns ~/.config/ocswitch/config.json (XDG aware).
func DefaultPath() string {
	if p := os.Getenv(ConfigEnvVar); p != "" {
		return p
	}
	if xdg := os.Getenv("XDG_CONFIG_HOME"); xdg != "" {
		return filepath.Join(xdg, ConfigDirName, "config.json")
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return AppName + "-config.json"
	}
	return filepath.Join(home, ".config", ConfigDirName, "config.json")
}

// Load reads the config at path. Missing file returns a default config anchored to path.
func Load(path string) (*Config, error) {
	if path == "" {
		path = DefaultPath()
	}
	c := Default()
	c.path = path
	data, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return c, nil
		}
		return nil, fmt.Errorf("read config: %w", err)
	}
	if len(data) == 0 {
		return c, nil
	}
	serverAPIKeyExplicit := configHasExplicitServerAPIKey(data)
	if err := json.Unmarshal(data, c); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	normalizeProviders(c.Providers)
	normalizeAliases(c.Aliases)
	normalizeRequestRewriteRules(c.RequestRewriteRules)
	c.ProviderPriority = c.normalizeProviderPriorityLocked(c.ProviderPriority)
	c.reorderUnlockedAutoAliasTargetsLocked()
	if c.Server.Host == "" {
		c.Server.Host = "127.0.0.1"
	}
	if c.Server.Port == 0 {
		c.Server.Port = 9982
	}
	if c.Server.APIKey == "" && !serverAPIKeyExplicit {
		c.Server.APIKey = DefaultLocalAPIKey
	}
	normalizeAdmin(&c.Admin)
	normalizeServerTimeouts(&c.Server)
	normalizeServerFailoverStatusCodes(&c.Server)
	normalizeServerRouting(&c.Server)
	c.path = path
	return c, nil
}

func configHasExplicitServerAPIKey(data []byte) bool {
	var raw struct {
		Server *struct {
			APIKey *string `json:"api_key"`
		} `json:"server"`
	}
	if err := json.Unmarshal(data, &raw); err != nil {
		return false
	}
	return raw.Server != nil && raw.Server.APIKey != nil
}

// Path returns the on-disk path of this config.
func (c *Config) Path() string {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.path
}

// MarshalPersistent encodes config using the same normalization and field set as Save.
func (c *Config) MarshalPersistent() ([]byte, error) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.marshalPersistentLocked()
}

func (c *Config) marshalPersistentLocked() ([]byte, error) {
	providers := cloneProviders(c.Providers)
	normalizeProviders(providers)
	sort.Slice(providers, func(i, j int) bool { return providers[i].ID < providers[j].ID })
	aliases := cloneAliases(c.Aliases)
	normalizeAliases(aliases)
	sort.Slice(aliases, func(i, j int) bool { return aliases[i].Alias < aliases[j].Alias })
	rewriteRules := cloneRequestRewriteRules(c.RequestRewriteRules)
	normalizeRequestRewriteRules(rewriteRules)
	server := c.Server
	normalizeServerTimeouts(&server)
	normalizeServerFailoverStatusCodes(&server)
	normalizeServerRouting(&server)
	snap := struct {
		Server              Server               `json:"server"`
		Admin               Admin                `json:"admin,omitempty"`
		Desktop             Desktop              `json:"desktop,omitempty"`
		Providers           []Provider           `json:"providers"`
		Aliases             []Alias              `json:"aliases"`
		RequestRewriteRules []RequestRewriteRule `json:"request_rewrite_rules,omitempty"`
		ProviderPriority    []string             `json:"provider_priority,omitempty"`
		// Persist explicitly so false is not dropped by omitempty on reload.
		AutoAliasEnabled bool `json:"auto_alias_enabled"`
	}{server, c.Admin, c.Desktop, providers, aliases, rewriteRules, cloneStrings(c.ProviderPriority), c.AutoAliasEnabled}
	data, err := json.MarshalIndent(snap, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	return append(data, '\n'), nil
}

// LoadFromBytes decodes config JSON for path without reading disk.
// Missing/empty data returns a default config anchored to path, matching Load.
func LoadFromBytes(path string, data []byte) (*Config, error) {
	if path == "" {
		path = DefaultPath()
	}
	c := Default()
	c.path = path
	if len(data) == 0 {
		return c, nil
	}
	serverAPIKeyExplicit := configHasExplicitServerAPIKey(data)
	if err := json.Unmarshal(data, c); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	normalizeProviders(c.Providers)
	normalizeAliases(c.Aliases)
	normalizeRequestRewriteRules(c.RequestRewriteRules)
	c.ProviderPriority = c.normalizeProviderPriorityLocked(c.ProviderPriority)
	c.reorderUnlockedAutoAliasTargetsLocked()
	if c.Server.Host == "" {
		c.Server.Host = "127.0.0.1"
	}
	if c.Server.Port == 0 {
		c.Server.Port = 9982
	}
	if c.Server.APIKey == "" && !serverAPIKeyExplicit {
		c.Server.APIKey = DefaultLocalAPIKey
	}
	normalizeAdmin(&c.Admin)
	normalizeServerTimeouts(&c.Server)
	normalizeServerFailoverStatusCodes(&c.Server)
	normalizeServerRouting(&c.Server)
	c.path = path
	return c, nil
}

// CloneDeep returns a detached deep copy of exported config fields.
func (c *Config) CloneDeep() (*Config, error) {
	raw, err := c.MarshalPersistent()
	if err != nil {
		return nil, err
	}
	return LoadFromBytes(c.Path(), raw)
}

// Save writes config atomically.
func (c *Config) Save() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.path == "" {
		c.path = DefaultPath()
	}
	path := c.path
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("mkdir: %w", err)
	}
	return fileutil.WithLockedFile(path, func() error {
		data, err := c.marshalPersistentLocked()
		if err != nil {
			return err
		}
		return fileutil.AtomicWriteFile(path, data, 0o600)
	})
}

// FindProvider returns the provider with matching id or nil.
func (c *Config) FindProvider(id string) *Provider {
	c.mu.RLock()
	defer c.mu.RUnlock()
	p := c.findProviderLocked(id)
	if p == nil {
		return nil
	}
	clone := cloneProvider(*p)
	return &clone
}

func (c *Config) findProviderLocked(id string) *Provider {
	for i := range c.Providers {
		if c.Providers[i].ID == id {
			return &c.Providers[i]
		}
	}
	return nil
}

// UpsertProvider adds or replaces a provider by id.
func (c *Config) UpsertProvider(p Provider) {
	c.mu.Lock()
	defer c.mu.Unlock()
	p.Protocol = NormalizeProviderProtocol(p.Protocol)
	cloned := cloneProvider(p)
	for i := range c.Providers {
		if c.Providers[i].ID == p.ID {
			c.Providers[i] = cloned
			return
		}
	}
	c.Providers = append(c.Providers, cloned)
}

// RemoveProvider deletes a provider and returns true if removed.
func (c *Config) RemoveProvider(id string) bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	for i := range c.Providers {
		if c.Providers[i].ID == id {
			c.Providers = append(c.Providers[:i], c.Providers[i+1:]...)
			return true
		}
	}
	return false
}

// FindAlias returns the manual (non-auto-generated) alias with matching name or nil.
func (c *Config) FindAlias(name string) *Alias {
	c.mu.RLock()
	defer c.mu.RUnlock()
	for i := range c.Aliases {
		if c.Aliases[i].Alias == name && !c.Aliases[i].AutoGenerated {
			clone := cloneAlias(c.Aliases[i])
			return &clone
		}
	}
	return nil
}

// FindAutoAlias returns the auto-generated alias with matching name or nil.
func (c *Config) FindAutoAlias(name string) *Alias {
	c.mu.RLock()
	defer c.mu.RUnlock()
	for i := range c.Aliases {
		if c.Aliases[i].Alias == name && c.Aliases[i].AutoGenerated {
			clone := cloneAlias(c.Aliases[i])
			return &clone
		}
	}
	return nil
}

// FindProvidersByModel returns enabled providers whose Models exactly contain
// model, ordered by the full provider priority list.
func (c *Config) FindProvidersByModel(model string) []Provider {
	c.mu.RLock()
	defer c.mu.RUnlock()
	model = strings.TrimSpace(model)
	if model == "" {
		return nil
	}
	matched := make(map[string]Provider, len(c.Providers))
	for _, p := range c.Providers {
		if !p.IsEnabled() {
			continue
		}
		if !providerModelsContain(p.Models, model) {
			continue
		}
		matched[p.ID] = cloneProvider(p)
	}
	if len(matched) == 0 {
		return nil
	}
	order := c.providerPriorityOrderLocked()
	out := make([]Provider, 0, len(matched))
	for _, id := range order {
		if p, ok := matched[id]; ok {
			out = append(out, p)
		}
	}
	return out
}

// SetProviderPriority sets the provider priority list. Unknown IDs are ignored,
// duplicates are dropped, and any remaining providers are appended in current
// config order. Unlocked auto-generated alias targets are reordered immediately.
func (c *Config) SetProviderPriority(ids []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.ProviderPriority = c.normalizeProviderPriorityLocked(ids)
	c.reorderUnlockedAutoAliasTargetsLocked()
}

// ProviderPriorityOrder returns the full priority list, including providers not
// explicitly listed in ProviderPriority.
func (c *Config) ProviderPriorityOrder() []string {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.providerPriorityOrderLocked()
}

// IsAutoAliasEnabled reports whether automatic alias generation is enabled.
// Defaults to true via Default() / Load().
func (c *Config) IsAutoAliasEnabled() bool {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.AutoAliasEnabled
}

// SetAutoAliasEnabled sets the global automatic alias generation switch.
func (c *Config) SetAutoAliasEnabled(enabled bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.AutoAliasEnabled = enabled
}

// LockAutoAlias marks an auto-generated alias as locked so automatic generation
// and cleanup no longer modify it. The alias remains AutoGenerated=true.
// Returns a clone of the locked alias.
func (c *Config) LockAutoAlias(name string) (Alias, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	name = strings.TrimSpace(name)
	if name == "" {
		return Alias{}, fmt.Errorf("alias name is required")
	}
	idx := c.findAliasIndexLocked(name)
	if idx < 0 {
		return Alias{}, fmt.Errorf("alias %q not found", name)
	}
	a := &c.Aliases[idx]
	if !a.AutoGenerated {
		return Alias{}, fmt.Errorf("alias %q is not auto-generated", name)
	}
	a.Locked = true
	return cloneAlias(*a), nil
}

// AutoGenerateAliases creates or updates unlocked auto-generated aliases for the
// provider's models. Manual and locked aliases are left untouched.
// Requires both the global switch and the provider's auto-alias switch.
func (c *Config) AutoGenerateAliases(provider Provider) (created []string, updated []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if !c.AutoAliasEnabled || !provider.EffectiveAutoAliasEnabled() {
		return nil, nil
	}
	provider.Protocol = NormalizeProviderProtocol(provider.Protocol)
	providerID := strings.TrimSpace(provider.ID)
	if providerID == "" {
		return nil, nil
	}
	for _, model := range provider.Models {
		model = strings.TrimSpace(model)
		if model == "" {
			continue
		}
		idx := c.findAliasIndexLocked(model)
		if idx < 0 {
			alias := Alias{
				Alias:         model,
				Protocol:      provider.Protocol,
				Enabled:       true,
				AutoGenerated: true,
				Targets: []Target{{
					Provider:      providerID,
					Model:         model,
					Enabled:       true,
					AutoGenerated: true,
				}},
			}
			c.Aliases = append(c.Aliases, cloneAlias(alias))
			created = append(created, model)
			continue
		}
		a := &c.Aliases[idx]
		if !a.AutoGenerated || a.Locked {
			continue
		}
		if !ProtocolsMatch(a.Protocol, provider.Protocol) {
			continue
		}
		if targetExists(a.Targets, providerID, model) {
			continue
		}
		a.Targets = append(a.Targets, Target{
			Provider:      providerID,
			Model:         model,
			Enabled:       true,
			AutoGenerated: true,
		})
		a.Targets = c.sortTargetsByPriorityLocked(a.Targets)
		updated = append(updated, model)
	}
	return created, updated
}

// RemoveProviderAutoTargets removes targets for providerID from unlocked
// auto-generated aliases. Aliases left with no targets are deleted; their names
// are returned in emptied. Manual aliases are not modified.
func (c *Config) RemoveProviderAutoTargets(providerID string) (emptied []string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	providerID = strings.TrimSpace(providerID)
	if providerID == "" {
		return nil
	}
	next := c.Aliases[:0]
	for i := range c.Aliases {
		a := c.Aliases[i]
		if !a.AutoGenerated || a.Locked {
			next = append(next, a)
			continue
		}
		kept := a.Targets[:0]
		for _, t := range a.Targets {
			if t.Provider == providerID {
				continue
			}
			kept = append(kept, t)
		}
		a.Targets = kept
		if len(a.Targets) == 0 {
			emptied = append(emptied, a.Alias)
			continue
		}
		next = append(next, a)
	}
	// Ensure Aliases is never nil-slice vs empty inconsistency if all removed.
	if len(next) == 0 {
		c.Aliases = []Alias{}
	} else {
		c.Aliases = next
	}
	return emptied
}

func (c *Config) findAliasIndexLocked(name string) int {
	for i := range c.Aliases {
		if c.Aliases[i].Alias == name {
			return i
		}
	}
	return -1
}

func (c *Config) providerPriorityOrderLocked() []string {
	return c.normalizeProviderPriorityLocked(c.ProviderPriority)
}

func (c *Config) normalizeProviderPriorityLocked(ids []string) []string {
	known := make(map[string]bool, len(c.Providers))
	for _, p := range c.Providers {
		if p.ID == "" {
			continue
		}
		known[p.ID] = true
	}
	seen := make(map[string]bool, len(c.Providers))
	out := make([]string, 0, len(c.Providers))
	for _, id := range ids {
		id = strings.TrimSpace(id)
		if id == "" || !known[id] || seen[id] {
			continue
		}
		seen[id] = true
		out = append(out, id)
	}
	for _, p := range c.Providers {
		if p.ID == "" || seen[p.ID] {
			continue
		}
		seen[p.ID] = true
		out = append(out, p.ID)
	}
	return out
}

func (c *Config) reorderUnlockedAutoAliasTargetsLocked() {
	for i := range c.Aliases {
		a := &c.Aliases[i]
		if !a.AutoGenerated || a.Locked {
			continue
		}
		a.Targets = c.sortTargetsByPriorityLocked(a.Targets)
	}
}

func (c *Config) sortTargetsByPriorityLocked(targets []Target) []Target {
	if len(targets) <= 1 {
		return cloneTargets(targets)
	}
	order := c.providerPriorityOrderLocked()
	rank := make(map[string]int, len(order))
	for i, id := range order {
		rank[id] = i
	}
	out := cloneTargets(targets)
	sort.SliceStable(out, func(i, j int) bool {
		ri, oki := rank[out[i].Provider]
		rj, okj := rank[out[j].Provider]
		if !oki {
			ri = len(order)
		}
		if !okj {
			rj = len(order)
		}
		if ri != rj {
			return ri < rj
		}
		return out[i].Model < out[j].Model
	})
	return out
}

