func normalizeTUILanguage(value string) string {
	if value == langZH {
		return langZH
	}
	return langEN
}

func translate(lang, key string, args ...any) string {
	lang = normalizeTUILanguage(lang)
	text := messages[lang][key]
	if text == "" {
		text = messages[langEN][key]
	}
	if text == "" {
		text = key
	}
	if len(args) == 0 {
		return text
	}
	return fmt.Sprintf(text, args...)
}
