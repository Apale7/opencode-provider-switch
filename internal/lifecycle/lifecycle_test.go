func TestPlanProviderRemoveNeverExpandsSingletonToWildcard(t *testing.T) {
	cfg := config.Default()
	cfg.Providers = []config.Provider{{ID: "only", BaseURL: "https://x.example/v1"}}
	cfg.RequestRewriteRules = []config.RequestRewriteRule{
		{Name: "s", Alias: "a", Providers: []string{"only"}, Enabled: true},
	}
	result, err := PlanProviderRemove(cfg, "rev", "only", nil)
	if err != nil {
		t.Fatal(err)
	}
	if result.Plan.Executable {
		t.Fatal("singleton rewrite must require choice")
	}
	found := false
	for _, c := range result.Plan.Choices {
		if c.Code == ReasonSingletonRewrite {
			found = true
			for _, opt := range c.Options {
				if opt.ID == OptionKeepDormant || opt.ID == OptionDisableRule || opt.ID == OptionDeleteRule || opt.ID == OptionReplaceProviders {
					continue
				}
				t.Fatalf("unexpected option %q", opt.ID)
			}
		}
	}
	if !found {
		t.Fatal("missing singleton rewrite choice")
	}
	// Automatic changes must not include rewriting singleton to empty.
	for _, ch := range result.Plan.AutomaticChanges {
		if ch.ReasonCode == ReasonRewriteSelectorNarrow {
			t.Fatalf("singleton must not be auto-narrowed: %+v", ch)
		}
	}
}

