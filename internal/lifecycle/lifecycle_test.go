func TestPlanAliasRemoveKeepsRewriteByDefaultChoice(t *testing.T) {
	cfg := baseConfig()
	// Alias manual is referenced by multi+single rewrite rules.
	selections := []Selection{
		{ChoiceID: "rewrite_on_alias_remove:0", OptionID: OptionKeepRule},
		{ChoiceID: "rewrite_on_alias_remove:1", OptionID: OptionDisableRule},
	}
	result, err := PlanAliasRemove(cfg, "rev", "manual", selections, ExternalRefs{
		OpenCodeModel: "manual",
	})
	if err != nil {
		t.Fatal(err)
	}
	if !result.Plan.Executable {
		t.Fatalf("plan=%+v", result.Plan)
	}
	if _, err := RequireUniqueAlias(result.Candidate, "manual"); err == nil {
		t.Fatal("alias should be removed")
	}
	var multi, single *config.RequestRewriteRule
	for i := range result.Candidate.RequestRewriteRules {
		r := &result.Candidate.RequestRewriteRules[i]
		switch r.Name {
		case "multi":
			multi = r
		case "single":
			single = r
		}
	}
	if multi == nil || multi.Alias != "manual" {
		t.Fatalf("keep rule lost: %+v", multi)
	}
	if single == nil || single.Enabled {
		t.Fatalf("disable rule failed: %+v", single)
	}
	foundOpenCode := false
	for _, issue := range result.Plan.PreservedIssues {
		if issue.Code == ReasonOpenCodeWeakRef {
			foundOpenCode = true
		}
		if issue.Code == ReasonDirectFallbackPossible {
			if v, _ := issue.Params["directFallbackPossible"].(bool); !v {
				t.Fatal("direct fallback flag missing")
			}
		}
	}
	if !foundOpenCode {
		t.Fatal("expected opencode weak ref preserved issue")
	}
}

