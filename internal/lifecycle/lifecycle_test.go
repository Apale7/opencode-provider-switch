func TestPlanGroupIDChangeDedupesCollidingTargetsAndSelectors(t *testing.T) {
	cfg := multiGroupConfig()
	// Dangling identities only: alias target + rewrite selector already reference
	// "gold", but no gold provider group exists yet. Renaming premium→gold must
	// execute and safely dedupe, not create duplicate identities.
	// Prefer the routable old target's Enabled/AutoGenerated over dangling properties.
	// (If a real gold group existed, that is a destination conflict — see Conflict test.)
	if p := cfg.FindProvider("vendor"); p == nil || p.FindGroup("gold") != nil {
		t.Fatal("fixture requires vendor without destination group gold")
	}

	idx, err := RequireUniqueAlias(cfg, "shared")
	if err != nil {
		t.Fatal(err)
	}
	// Mark old premium target with distinctive props so we can prove they survive.
	for ti := range cfg.Aliases[idx].Targets {
		tget := &cfg.Aliases[idx].Targets[ti]
		if tget.Group == "premium" && tget.Model == "shared" {
			tget.Enabled = false
			tget.AutoGenerated = false
		}
	}
	// shared already has default+premium; add dangling gold for same model with opposite props.
	cfg.Aliases[idx].Targets = append(cfg.Aliases[idx].Targets, config.Target{
		Provider: "vendor", Group: "gold", Model: "shared", Enabled: true, AutoGenerated: true,
	})
	// multi-groups has default+premium; add dangling gold so premium→gold collides.
	for i := range cfg.RequestRewriteRules {
		if cfg.RequestRewriteRules[i].Name == "multi-groups" {
			cfg.RequestRewriteRules[i].ProviderGroups = append(cfg.RequestRewriteRules[i].ProviderGroups,
				config.ProviderGroupSelector{Provider: "vendor", Group: "gold"},
			)
		}
	}

	result, err := PlanGroupIDChange(cfg, "rev", "vendor", "premium", "gold", nil)
	if err != nil {
		t.Fatal(err)
	}
	if !result.Plan.Executable {
		t.Fatalf("plan should execute with dangling-identity dedupe: blockers=%+v", result.Plan.Blockers)
	}
	dedupeTarget := false
	dedupeRewrite := false
	retargetOld := false
	for _, ch := range result.Plan.AutomaticChanges {
		if action, _ := ch.Params["action"].(string); action == "dedupe_collision" {
			if ch.Entity == EntityAliasTarget {
				dedupeTarget = true
			}
			if ch.Entity == EntityRewriteRule {
				dedupeRewrite = true
			}
		}
		if ch.Entity == EntityAliasTarget && ch.Kind == ChangeUpdate {
			if oldG, _ := ch.Params["oldGroupId"].(string); oldG == "premium" {
				retargetOld = true
			}
		}
	}
	if !dedupeTarget {
		t.Fatalf("expected dangling target remove automatic change, got %+v", result.Plan.AutomaticChanges)
	}
	if !dedupeRewrite {
		t.Fatalf("expected rewrite selector dedupe automatic change, got %+v", result.Plan.AutomaticChanges)
	}
	if !retargetOld {
		t.Fatalf("expected old target retarget automatic change, got %+v", result.Plan.AutomaticChanges)
	}

	// Candidate: premium renamed to gold; only one shared target at gold; multi-groups unique gold once.
	p := result.Candidate.FindProvider("vendor")
	if p == nil || p.FindGroup("premium") != nil || p.FindGroup("gold") == nil {
		t.Fatalf("expected premium→gold rename on groups, got %+v", p)
	}
	aidx, err := RequireUniqueAlias(result.Candidate, "shared")
	if err != nil {
		t.Fatal(err)
	}
	goldCount := 0
	var goldTarget *config.Target
	for i := range result.Candidate.Aliases[aidx].Targets {
		tget := &result.Candidate.Aliases[aidx].Targets[i]
		if tget.Group == "premium" {
			t.Fatal("premium target should be gone")
		}
		if tget.Provider == "vendor" && tget.Group == "gold" && tget.Model == "shared" {
			goldCount++
			goldTarget = tget
		}
	}
	if goldCount != 1 {
		t.Fatalf("gold shared targets = %d, want 1; targets=%+v", goldCount, result.Candidate.Aliases[aidx].Targets)
	}
	// Must keep routable old properties, not dangling Enabled/AutoGenerated.
	if goldTarget == nil || goldTarget.Enabled || goldTarget.AutoGenerated {
		t.Fatalf("gold target must preserve old props (Enabled=false, AutoGenerated=false), got %+v", goldTarget)
	}
	for _, rule := range result.Candidate.RequestRewriteRules {
		if rule.Name != "multi-groups" {
			continue
		}
		seen := map[string]int{}
		for _, sel := range rule.ProviderGroups {
			seen[sel.Provider+"/"+sel.Group]++
		}
		if seen["vendor/gold"] != 1 {
			t.Fatalf("multi-groups selectors not deduped: %+v", rule.ProviderGroups)
		}
		if seen["vendor/premium"] != 0 {
			t.Fatalf("premium selector remained: %+v", rule.ProviderGroups)
		}
	}
}

func TestPlanGroupRemoveDuplicateTargetsByIndex(t *testing.T) {
	// Two protected targets share the same (alias, provider, group, model) identity
	// but live at different targetIndex values. Selections must apply by index so
	// remove and rebind do not overwrite each other.
	cfg := config.Default()
	cfg.Providers = []config.Provider{{
		ID: "vendor", BaseURL: "https://vendor.example/v1",
		Groups: []config.ProviderGroup{
			{ID: "default", Protocol: config.ProtocolOpenAIResponses, Models: []string{"shared"}},
			{ID: "premium", Protocol: config.ProtocolOpenAIResponses, Models: []string{"shared"}},
		},
	}}
	cfg.Aliases = []config.Alias{{
		Alias: "dup", Enabled: true,
		Protocol: config.ProtocolOpenAIResponses,
		Targets: []config.Target{
			{Provider: "vendor", Group: "premium", Model: "shared", Enabled: true},
			{Provider: "vendor", Group: "premium", Model: "shared", Enabled: false},
		},
	}}
	cfg.RequestRewriteRules = nil

	result, err := PlanGroupRemove(cfg, "rev", "vendor", "premium", []Selection{
		{ChoiceID: "protected_target:0:0", OptionID: OptionRemoveTarget},
		{ChoiceID: "protected_target:0:1", OptionID: OptionRebindTarget, Params: map[string]any{
			"providerId": "vendor", "groupId": "default", "model": "shared",
		}},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !result.Plan.Executable {
		t.Fatalf("expected executable with per-index selections: blockers=%+v choices=%+v", result.Plan.Blockers, result.Plan.Choices)
	}
	if len(result.Plan.Choices) != 2 {
		t.Fatalf("want 2 precise choices, got %+v", result.Plan.Choices)
	}
	for _, c := range result.Plan.Choices {
		if c.ID != "protected_target:0:0" && c.ID != "protected_target:0:1" {
			t.Fatalf("choice id must be aliasIndex:targetIndex precise, got %q", c.ID)
		}
	}
	aidx, err := RequireUniqueAlias(result.Candidate, "dup")
	if err != nil {
		t.Fatal(err)
	}
	targets := result.Candidate.Aliases[aidx].Targets
	if len(targets) != 1 {
		t.Fatalf("want 1 remaining target after remove+rebind, got %+v", targets)
	}
	// Only targetIndex 1 survives, rebound to default, preserving original Enabled=false.
	if targets[0].Group != "default" || targets[0].Model != "shared" || targets[0].Enabled {
		t.Fatalf("rebind must act on targetIndex 1 only: %+v", targets[0])
	}
	if targets[0].AutoGenerated {
		t.Fatal("rebind must clear AutoGenerated")
	}
}

