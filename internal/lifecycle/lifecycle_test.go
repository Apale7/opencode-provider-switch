func baseConfig() *config.Config {
	cfg := config.Default()
	cfg.Providers = []config.Provider{
		{ID: "p1", BaseURL: "https://p1.example/v1"},
		{ID: "p2", BaseURL: "https://p2.example/v1"},
	}
	cfg.ProviderPriority = []string{"p1", "p2"}
	cfg.Aliases = []config.Alias{
		{
			Alias: "sys-model", AutoGenerated: true, Enabled: true,
			Targets: []config.Target{
				{Provider: "p1", Model: "sys-model", Enabled: true, AutoGenerated: true},
				{Provider: "p2", Model: "sys-model", Enabled: true, AutoGenerated: true},
			},
		},
		{
			Alias: "manual", Enabled: true,
			Targets: []config.Target{{Provider: "p1", Model: "m", Enabled: true}},
		},
		{
			Alias: "mixed", AutoGenerated: true, Enabled: true,
			Targets: []config.Target{
				{Provider: "p1", Model: "a", Enabled: true, AutoGenerated: true},
				{Provider: "p1", Model: "b", Enabled: true, AutoGenerated: false},
			},
		},
		{
			Alias: "locked", AutoGenerated: true, Locked: true, Enabled: true,
			Targets: []config.Target{{Provider: "p1", Model: "L", Enabled: true, AutoGenerated: true}},
		},
	}
	cfg.RequestRewriteRules = []config.RequestRewriteRule{
		{Name: "multi", Alias: "manual", Providers: []string{"p1", "p2"}, Enabled: true},
		{Name: "single", Alias: "manual", Providers: []string{"p1"}, Enabled: true},
		{Name: "wild", Alias: "other", Providers: nil, Enabled: true},
	}
	return cfg
}

func TestPlanProviderRemoveSystemAndPriorityAndNarrow(t *testing.T) {
	cfg := baseConfig()
	// Resolve protected targets and singleton rewrite.
	selections := []Selection{
		{ChoiceID: "protected_target:1:0", OptionID: OptionRemoveTarget}, // manual
		{ChoiceID: "protected_target:2:1", OptionID: OptionRemoveTarget}, // mixed protected b
		{ChoiceID: "protected_target:3:0", OptionID: OptionDeleteAlias},  // locked
		{ChoiceID: "singleton_rewrite:1", OptionID: OptionKeepDormant},
	}
	result, err := PlanProviderRemove(cfg, "rev-base", "p1", selections)
	if err != nil {
		t.Fatal(err)
	}
	if !result.Plan.Executable {
		t.Fatalf("expected executable plan, got blockers=%+v choices=%+v", result.Plan.Blockers, result.Plan.Choices)
	}
	if result.Candidate == nil {
		t.Fatal("missing candidate")
	}
	if result.Candidate.FindProvider("p1") != nil {
		t.Fatal("provider p1 still present")
	}
	for _, id := range result.Candidate.ProviderPriority {
		if id == "p1" {
			t.Fatal("priority retained p1")
		}
	}
	// multi rewrite narrowed to [p2]
	var multi *config.RequestRewriteRule
	for i := range result.Candidate.RequestRewriteRules {
		if result.Candidate.RequestRewriteRules[i].Name == "multi" {
			multi = &result.Candidate.RequestRewriteRules[i]
		}
	}
	if multi == nil || len(multi.Providers) != 1 || multi.Providers[0] != "p2" {
		t.Fatalf("multi rewrite not narrowed: %+v", multi)
	}
	// singleton kept dormant with p1
	var single *config.RequestRewriteRule
	for i := range result.Candidate.RequestRewriteRules {
		if result.Candidate.RequestRewriteRules[i].Name == "single" {
			single = &result.Candidate.RequestRewriteRules[i]
		}
	}
	if single == nil || len(single.Providers) != 1 || single.Providers[0] != "p1" {
		t.Fatalf("singleton must stay dormant, got %+v", single)
	}
	// wildcard unchanged
	for _, rule := range result.Candidate.RequestRewriteRules {
		if rule.Name == "wild" && len(rule.Providers) != 0 {
			t.Fatalf("wildcard changed: %+v", rule)
		}
	}
	// locked alias deleted via selection
	if idx, _ := RequireUniqueAlias(result.Candidate, "locked"); idx >= 0 {
		t.Fatal("locked alias should be deleted by selection")
	}
	// pure auto sys-model still has p2 target
	idx, err := RequireUniqueAlias(result.Candidate, "sys-model")
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Candidate.Aliases[idx].Targets) != 1 || result.Candidate.Aliases[idx].Targets[0].Provider != "p2" {
		t.Fatalf("sys-model targets=%+v", result.Candidate.Aliases[idx].Targets)
	}
}

