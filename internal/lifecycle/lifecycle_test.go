func TestPlanDiscoveryTrustedPrunesOnlySystemTargets(t *testing.T) {
	cfg := baseConfig()
	result, err := PlanDiscoveryReconcile(cfg, "rev", "p1", DiscoveryObservation{
		Status: DiscoveryTrustedComplete,
		Models: []string{"other"}, // sys-model gone for p1
	})
	if err != nil {
		t.Fatal(err)
	}
	if !result.Plan.Executable {
		t.Fatalf("plan=%+v", result.Plan)
	}
	// sys-model: p1 system target removed, p2 remains
	idx, err := RequireUniqueAlias(result.Candidate, "sys-model")
	if err != nil {
		t.Fatal(err)
	}
	for _, tget := range result.Candidate.Aliases[idx].Targets {
		if tget.Provider == "p1" {
			t.Fatalf("system target for p1 retained: %+v", tget)
		}
	}
	// mixed: system a may be removed; protected b retained
	idx, err = RequireUniqueAlias(result.Candidate, "mixed")
	if err != nil {
		t.Fatal(err)
	}
	foundProtected := false
	for _, tget := range result.Candidate.Aliases[idx].Targets {
		if tget.Model == "a" && tget.Provider == "p1" {
			t.Fatal("system target a should be pruned")
		}
		if tget.Model == "b" {
			foundProtected = true
		}
	}
	if !foundProtected {
		t.Fatal("protected target b removed")
	}
	// locked untouched
	idx, err = RequireUniqueAlias(result.Candidate, "locked")
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Candidate.Aliases[idx].Targets) != 1 {
		t.Fatal("locked alias mutated")
	}
	// manual untouched
	idx, err = RequireUniqueAlias(result.Candidate, "manual")
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Candidate.Aliases[idx].Targets) != 1 {
		t.Fatal("manual alias mutated")
	}
}

